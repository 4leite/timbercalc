  const waterExact = workerRecipeExact(p * 2.13, { prodAmount: 1, prodTime: 0.33 }, options)
  const tapperShackExact = gatherBuildingExact(mapleTreePerDay, 2.5, 1, options)
  const gathererFlagExact = gatherBuildingExact(chestnutTreePerDay, 1.2, 1, options)
