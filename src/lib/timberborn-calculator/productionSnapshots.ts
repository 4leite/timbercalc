const escapedRegExp = (expected: string): string => expected.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

const productionRowStartPattern = new RegExp(
  `(?:^|\\s)(?:total|\\d+(?:\\.\\d+)?\\s+(?:${productionRowLabels
    .map(escapedRegExp)
    .join("|")})(?=\\s|$))`,
  "gi",
)

const nutritionProductionRows = (body: string): NutritionProductionSnapshotRow[] => {
  const rowMatches = [...body.matchAll(productionRowStartPattern)]

  if (rowMatches.length === 0) {
    return [{ text: body }]
  }

  return rowMatches.map((match, index) => {
    const bodyStart = match.index ?? 0
    const rowStart = body[bodyStart] === " " ? bodyStart + 1 : bodyStart
    const rowEnd = rowMatches[index + 1]?.index ?? body.length

    return { text: body.slice(rowStart, rowEnd).trim() }
  })
}

export const nutritionProductionSnapshotSectionsFromText = (
  snapshot: string,
  key: string,
): NutritionProductionSnapshotSection[] => {
  const headerIndex = snapshot.indexOf(productionColumnHeader)

  if (headerIndex === -1) {
    throw new Error(`Unexpected Nutrition production snapshot header for ${key}`)
  }

  const productionBody = snapshot.slice(headerIndex + productionColumnHeader.length)
  const sectionPattern = /(?:^|\s)▾ (water|crops|trees|food|wood|metal|science)\s/gi
  const sectionMatches = [...productionBody.matchAll(sectionPattern)]

  return sectionMatches.map((match, index) => {
    const title = match[1]
    const bodyStart = (match.index ?? 0) + match[0].length
    const nextSectionStart = sectionMatches[index + 1]?.index ?? productionBody.length

    const body = productionBody.slice(bodyStart, nextSectionStart).trim()

    return {
      title: productionSectionTitle(title),
      body,
      rows: nutritionProductionRows(body),
    }
  })
}

export const nutritionProductionSnapshotSections = (
  key: NutritionProductionSnapshotKey,
): NutritionProductionSnapshotSection[] => {
  return nutritionProductionSnapshotSectionsFromText(nutritionProductionSnapshots[key], key)
}
