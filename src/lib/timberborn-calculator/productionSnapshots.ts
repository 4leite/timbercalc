export type NutritionProductionSnapshotKey = keyof typeof nutritionProductionSnapshots

export type NutritionProductionSnapshotSection = {
  title: string
  body: string
  rows: NutritionProductionSnapshotRow[]
}

export type NutritionProductionSnapshotRow = {
  text: string
}

const productionColumnHeader =
  "item/day needed building/plants needed land use workers power/day bots "

const productionSectionTitle = (title: string): string => {
  return title.slice(0, 1).toUpperCase() + title.slice(1)
}

