  const waterPumpBuildings = ceilReference(waterExact)
  const tapperShackBuildings = ceilReference(tapperShackExact)
  const gathererFlagBuildings = ceilReference(gathererFlagExact)
  const efficientFarmhouseBuildings = ceilReference(efficientFarmhouseExact)
  const aquaticFarmhouseBuildings = ceilReference(aquaticFarmhouseExact)
  const lumberjackFlagBuildings = ceilReference(lumberjackFlagExact)
  const workerRecipeBuildings = p > 0 ? 8 : 0
  const productionTableWorkers =
    waterPumpBuildings +
    tapperShackBuildings +
    gathererFlagBuildings +
    positiveWorkerSlots(efficientFarmhouseExact, 3) +
    positiveWorkerSlots(aquaticFarmhouseExact, 2) +
    workerRecipeBuildings +
    lumberjackFlagBuildings
  const productionBuildingsWithWater =
    waterPumpBuildings +
    tapperShackBuildings +
    gathererFlagBuildings +
    efficientFarmhouseBuildings +
    aquaticFarmhouseBuildings +
    workerRecipeBuildings +
    lumberjackFlagBuildings
