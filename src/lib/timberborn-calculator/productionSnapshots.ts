    waterPumpBuildings * 4 +
    tapperShackBuildings * 4 +
    gathererFlagBuildings +
    efficientFarmhouseBuildings * 6 +
    aquaticFarmhouseBuildings * 6 +
    (p > 0 ? 42 : 0) +
    lumberjackFlagBuildings
  const availableBeavers = p <= 3 ? p : p <= 19 ? Math.ceil(p - 1) : Math.ceil(p - 2)
  const workingBeavers = productionTableWorkers + 1
  const availableCarriers = Math.max(0, availableBeavers - workingBeavers)
  const availableCarrierPercent = Math.round(
    (availableCarriers / Math.max(1, availableBeavers)) * 100,
  )
  const production = p * (71 / 12)
  const gristmillBuildings = p > 0 ? 2 : 0
  const hpUsed = gristmillBuildings * 60 * baseWorkHours
  const hpGenerated =
    p > 0
      ? DEFAULT_WATER_WHEEL_HP_PER_DAY + 50 * effectiveWorkHours * NUTRITION_BEAVER_MOVE_SPEED
      : 0

