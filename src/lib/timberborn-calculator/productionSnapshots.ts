const roundTo = (value: number, decimals: number) => {
  return Number(value.toFixed(decimals))
}

const formattedMagnitude = (value: number) => {
  const magnitude = Math.abs(value)

  if (magnitude < 10) {
    return value.toFixed(2)
  }

  if (magnitude < 100) {
    return (Math.round(value * 10) / 10).toFixed(1)
  }

  return String(Math.round(value))
}

const formattedRecapMagnitude = (value: number) => {
  return value % 1 === 0 ? String(Math.round(value)) : value.toFixed(1)
}

const formattedCompactMagnitude = (value: number) => {
  const rounded =
    Math.abs(value) < 10
      ? roundTo(value, 2)
      : Math.abs(value) < 100
        ? roundTo(value, 1)
        : Math.round(value)

  return String(rounded)
}

const fixedExact = (value: number) => value.toFixed(2)

const ceilPositive = (value: number) => Math.ceil(Math.max(0, value))

const ceilReference = (value: number) => (value > 0 ? Math.ceil(value - 1e-12) : 0)

const FOLKTAIL_NUTRITION_AMOUNTS = [0.25, 0.1, 0.25, 0.25, 0.25, 0.25, 0.25, 0.25] as const

const DEFAULT_HUNGER_PER_BEAVER = 2.67
const DEFAULT_HUNGER_POOL_SHARE = 12.5 / 100

const defaultHungerRemainderPerBeaver = () => {
  let nutritionConsumption = 0

  for (const amount of FOLKTAIL_NUTRITION_AMOUNTS) {
    nutritionConsumption += amount
  }

  return Math.max(0, DEFAULT_HUNGER_PER_BEAVER - nutritionConsumption)
}

const productionRowRequiredShare = (demandPerDay: number) => {
  return (demandPerDay * 100) / 100
}

const nutritionDemandWithHunger = (population: number, directPerBeaver: number) => {
  const directDemand = population * directPerBeaver
  const hungerDemand = population * defaultHungerRemainderPerBeaver() * DEFAULT_HUNGER_POOL_SHARE

  return productionRowRequiredShare(directDemand + hungerDemand)
}

const recipeInputDemand = (requiredShare: number, inputAmount: number, outputAmount: number) => {
  return productionRowRequiredShare(requiredShare * (inputAmount / outputAmount))
}

const positiveWorkerSlots = (buildingExact: number, workerCapacity: number) => {
  return buildingExact > 0 ? Math.max(1, Math.ceil(buildingExact * workerCapacity)) : 0
}

const nutritionTime = ({
  workingHours = 16,
  wanderingTime = 0.5,
}: NutritionProductionOptions = {}) => {
  const shelterSleepHours = 4
  const sleepPenaltyHours = 2
  const baseWorkHours =
    workingHours + shelterSleepHours > 24
      ? 24 - shelterSleepHours - sleepPenaltyHours
      : workingHours

  return {
    baseWorkHours: Math.max(0, baseWorkHours),
    effectiveWorkHours: Math.max(0, baseWorkHours - wanderingTime),
  }
}

const NUTRITION_BEAVER_WORK_SPEED = 1.6
const NUTRITION_BEAVER_MOVE_SPEED = 1.15
const DEFAULT_WATER_WHEEL_HP_PER_DAY = 1638

const workerRecipeExact = (
  requiredPerDay: number,
  recipe: { prodAmount: number; prodTime: number },
  options?: NutritionProductionOptions,
) => {
  const { effectiveWorkHours } = nutritionTime(options)
  const capacityPerDay =
    (recipe.prodAmount / recipe.prodTime) * effectiveWorkHours * NUTRITION_BEAVER_WORK_SPEED

  return capacityPerDay > 0 ? requiredPerDay / capacityPerDay : 0
}

const gatherBuildingExact = (
  plantsPerDay: number,
  gatherTimeHours: number,
  workerCapacity: number,
  options?: NutritionProductionOptions,
) => {
  const { effectiveWorkHours } = nutritionTime(options)
  const capacityPerDay = workerCapacity * effectiveWorkHours * NUTRITION_BEAVER_WORK_SPEED

  return capacityPerDay > 0 ? (plantsPerDay * gatherTimeHours) / capacityPerDay : 0
}

const workerRecipeAssignedOutput = (
  buildingCount: number,
  recipe: { prodAmount: number; prodTime: number },
  options?: NutritionProductionOptions,
) => {
  const { effectiveWorkHours } = nutritionTime(options)
  return (
    buildingCount *
    (recipe.prodAmount / recipe.prodTime) *
    effectiveWorkHours *
    NUTRITION_BEAVER_WORK_SPEED
  )
}

const displayedRequiredShare = (requiredPerDay: number, assignedOutput: number) => {
  return formattedMagnitude(assignedOutput - (assignedOutput - requiredPerDay))
}

const formatHp = (value: number, casing: "upper" | "lower" = "upper") => {
  const unit = casing === "upper" ? "Khp" : "khp"

  if (Math.abs(value) >= 1000) {
    return `${parseFloat((value / 1000).toFixed(2))} ${unit}`
  }

  return `${Math.round(value)} hp`
}

const formatNet = (value: number) => {
  const sign = value >= 0 ? "+" : ""
  return `${sign}${formatHp(value)}`
}

